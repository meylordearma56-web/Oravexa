window.OravexaI18n = {
  getLang() {
    const saved = localStorage.getItem("oravexaLang");
    return saved === "es" ? "es" : "en";
  },
  setLang(lang) {
    const next = lang === "es" ? "es" : "en";
    localStorage.setItem("oravexaLang", next);
    document.documentElement.setAttribute("lang", next);
  },
  t(key, vars = {}) {
    const lang = this.getLang();
    let text = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
  },
  localizeArticle(article) {
    if (!article) return article;
    const es = this.getLang() === "es";
    return {
      ...article,
      displayTitle: es ? article.titleEs || article.title : article.title,
      displaySummary: es ? article.summaryEs || article.summary : article.summary,
      displayCategories: es
        ? article.categoriesEs || article.categories || []
        : article.categories || [],
      displayHtml: es ? article.htmlEs || article.html : article.html,
      displayContent: es ? article.contentEs || article.content : article.content,
    };
  },
  categoryName(name) {
    if (this.getLang() !== "es") return name;
    return CATEGORY_ES[name] || name;
  },
};
